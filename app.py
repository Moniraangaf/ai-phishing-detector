labels = [0] * len(good_messages) + [1] * len(bad_messages)

df = pd.DataFrame({"text": texts, "label": labels})

# -------------------- ВЕКТОРИЗАТОР --------------------
vectorizer = TfidfVectorizer(
    ngram_range=(1, 2),      # учитываем отдельные слова и биграммы
    min_df=1,                # ничего не выкидываем (данных мало)
    max_df=0.9,              # игнорируем слова, которые встречаются почти везде
    lowercase=True,
)

X = vectorizer.fit_transform(df["text"])
y = df["label"]

# -------------------- МОДЕЛЬ --------------------
model = LogisticRegression(
    C=5.0,                   # ослабляем регуляризацию, распределение вероятностей шире
    max_iter=1000,
    solver="liblinear"       # хорошо работает на маленьких датасетах
)
model.fit(X, y)


